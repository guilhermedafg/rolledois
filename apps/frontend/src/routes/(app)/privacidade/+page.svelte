    <h1>Política de Privacidade do Rolle</h1>

    <p><i>Última atualização: 16 de junho de 2026</i></p>

    <h2>1. Introdução</h2>

    <p>
        O rolle é uma plataforma de descoberta urbana baseada em curadoria humana, que ajuda pessoas
        a salvar, organizar e descobrir lugares. Levamos a sua privacidade a sério. Esta Política de
        Privacidade explica quais dados pessoais coletamos, como os usamos, com quem compartilhamos
        e quais são os seus direitos quando você utiliza nosso aplicativo, site e nosso assistente
        automatizado no Instagram (em conjunto, o "Serviço").
    </p>

    <p>
        Esta Política é regida pela
        <strong> Lei nº 13.709/2018 (Lei Geral de Proteção de Dados Pessoais – LGPD)</strong>. Ao
        utilizar o Serviço, você declara estar ciente desta Política. Caso não concorde com seus
        termos, por favor, não utilize o Serviço.
    </p>

    <p>
        <strong>Controlador dos dados:</strong> Rolle LTDA, inscrito no CNPJ sob nº 66.037.538/0001-89,
        com sede em Av. Vicente Machado, 160 - Centro, Curitiba - PR, 80420-010.
    </p>

    <h2>2. Quais dados pessoais coletamos</h2>

    <h3>2.1. Dados de cadastro</h3>

    <p>
        Quando você cria uma conta, coletamos seu nome, endereço de e-mail e credenciais de
        autenticação. Se você entra com sua conta Google, recebemos apenas as informações que você
        autoriza no momento do login.
    </p>

    <h3>2.2 Uso de dados</h3>

    <p>Coletamos automaticamente certas informações quando você usa o Serviço, incluindo:</p>

    <ul>
        <li>Links que você compartilha com o Serviço para extração de locais</li>
        <li>Locais salvos no seu perfil pessoal</li>
        <li>Padrões de uso do aplicativo e interações com recursos</li>
        <li>
            Informações do dispositivo (tipo de dispositivo, sistema operacional, versão do
            aplicativo)
        </li>
    </ul>

    <h3>2.3 Conteudo de Media Social</h3>

    <p>
        Ao compartilhar um link do Instagram ou de outras plataformas compatíveis, acessamos o
        conteúdo público disponível nesse URL para extrair informações sobre o local. Não acessamos
        suas contas de redes sociais nem seu conteúdo privado.
    </p>

    <h2>3. Como usamos os seus dados</h2>

    <p>Tratamos seus dados pessoais para as seguintes finalidades:</p>

    <ul>
        <li>
            <strong>Prestar o Serviço</strong>, incluindo a extração de lugares por inteligência
            artificial a partir do conteúdo que você encaminha;
        </li>
        <li><strong>Criar e administrar a sua conta</strong>;</li>
        <li>
            <strong>Salvar e organizar os lugares</strong> no seu rolle e habilitar os recursos de curadoria
            e comunidade;
        </li>
        <li>
            <strong>Aprimorar a qualidade do Serviço</strong> e a precisão da nossa extração por IA;
        </li>
        <li>
            <strong>Enviar comunicações essenciais</strong> sobre o Serviço (avisos operacionais, de segurança
            e atualizações relevantes);
        </li>
        <li><strong>Responder às suas solicitações</strong> e prestar suporte;</li>
        <li>
            <strong>Garantir segurança</strong>, prevenir fraudes e abusos e cumprir obrigações
            legais.
        </li>
    </ul>

    <h3>Bases legais (LGPD)</h3>

    <p>
        Tratamos seus dados com fundamento nas seguintes hipóteses do Art. 7º da LGPD:
        <strong>execução de contrato</strong>
        (para prestar o Serviço que você solicitou), <strong>consentimento</strong> (por exemplo, ao
        conectar sua conta do Instagram e encaminhar conteúdo), <strong>legítimo interesse</strong>
        (para melhorar e dar segurança ao Serviço) e
        <strong>cumprimento de obrigação legal ou regulatória</strong>.
    </p>

    <h2>4. Compartilhamento de dados e operadores</h2>

    <p>
        Seus lugares salvos são <strong>privados por padrão</strong>. Nós
        <strong>não vendemos</strong> seus dados pessoais. Compartilhamos dados apenas nas seguintes situações:
    </p>

    <h3>4.1. Operadores (prestadores de serviço)</h3>

    <p>
        Utilizamos parceiros que tratam dados em nosso nome, exclusivamente para operar o Serviço:
    </p>

    <ul>
        <li>
            <strong>Meta Platforms, Inc.</strong> — por meio da Messaging API do Instagram, para receber
            o conteúdo que você encaminha e enviar as respostas do assistente no seu DM;
        </li>
        <li>
            <strong>Google Places</strong> para a geocodificação e o enriquecimento das informações dos
            lugares;
        </li>
        <li>
            <strong>Open AI GPT</strong> para o enriquecimento das informações dos lugares;
        </li>
        <li>
            <strong>Provedor de autenticação</strong> (Google), para gerenciar o acesso à sua conta.
        </li>
    </ul>

    <h3>4.2. Por sua determinação</h3>

    <p>
        Quando você compartilha listas ou lugares com outras pessoas, esse conteúdo se torna visível
        para aqueles com quem você optou por compartilhar.
    </p>

    <h3>4.3. Exigências legais</h3>

    <p>
        Podemos divulgar dados se exigido por lei ou em resposta a solicitações legais válidas de
        autoridades competentes.
    </p>

    <h2>5. Uso de dados da Plataforma Meta</h2>

    <p>
        O uso, por parte do rolle, de informações recebidas das APIs da Meta (Instagram) está em
        conformidade com os <strong>Termos da Plataforma Meta</strong> e as
        <strong>Políticas para Desenvolvedores da Meta</strong>. Os dados obtidos por meio dessas
        APIs são utilizados <strong>somente</strong> para fornecer e aprimorar as funcionalidades
        descritas nesta Política. Nós <strong>não</strong> vendemos esses dados,
        <strong>não</strong>
        os utilizamos para publicidade direcionada e <strong>não</strong> os transferimos a terceiros,
        exceto aos operadores estritamente necessários à prestação do Serviço, conforme descrito acima.
    </p>

    <h2>6. Transferência internacional de dados</h2>

    <p>
        Alguns dos nossos operadores (como a Meta e o Google) podem tratar dados em servidores
        localizados fora do Brasil, inclusive nos Estados Unidos. Nesses casos, adotamos as
        salvaguardas exigidas pela LGPD para garantir um nível adequado de proteção aos seus dados
        pessoais.
    </p>

    <h2>7. Armazenamento e segurança</h2>

    <p>
        Seus dados são armazenados em servidores de provedores de nuvem contratados. Utilizamos
        medidas técnicas e administrativas para proteger seus dados, incluindo criptografia em
        trânsito (TLS). Embora adotemos práticas de segurança razoáveis de mercado, nenhum método de
        transmissão ou armazenamento é 100% seguro.
    </p>

    <h2>8. Retenção e exclusão de dados</h2>

    <p>
        Mantemos seus dados de cadastro e seus lugares salvos enquanto sua conta estiver ativa. Caso
        você exclua sua conta, eliminaremos seus dados pessoais no prazo de
        <strong>30 dias</strong>
        , ressalvadas as hipóteses em que a retenção seja exigida por obrigação legal.
    </p>

    <h3>Como solicitar a exclusão dos seus dados</h3>

    <p>
        Você pode solicitar a exclusão dos seus dados,
        <strong>incluindo os dados vinculados ao seu Instagram</strong>
        , das seguintes formas:
    </p>

    <ol>
        <li>Pelas configurações da sua conta no aplicativo; ou</li>
        <li>
            Enviando um e-mail para <strong>excluir@rolle.com.br</strong>, a partir do qual
            processaremos sua solicitação e desvincularemos seu IGSID dos nossos sistemas.
        </li>
    </ol>

    <h2>9. Seus direitos como titular (LGPD)</h2>

    <p>Nos termos do Art. 18 da LGPD, você tem o direito de, a qualquer momento, solicitar:</p>

    <ul>
        <li>A <strong>confirmação</strong> da existência de tratamento dos seus dados;</li>
        <li>O <strong>acesso</strong> aos seus dados;</li>
        <li>A <strong>correção</strong> de dados incompletos, inexatos ou desatualizados;</li>
        <li>
            A <strong>anonimização, bloqueio ou eliminação</strong> de dados desnecessários ou tratados
            em desconformidade com a lei;
        </li>
        <li>A <strong>portabilidade</strong> dos seus dados;</li>
        <li>A <strong>eliminação</strong> dos dados tratados com base no seu consentimento;</li>
        <li>
            A <strong>informação</strong> sobre as entidades com as quais compartilhamos seus dados;
        </li>
        <li>A <strong>revogação do consentimento</strong>.</li>
    </ul>

    <p>
        Para exercer qualquer um desses direitos, entre em contato pelo e-mail
        <strong>contato@rolle.com.br</strong> . Você também tem o direito de peticionar à
        <strong>Autoridade Nacional de Proteção de Dados (ANPD)</strong>.
    </p>

    <h2>10. Encarregado pelo Tratamento de Dados (DPO)</h2>

    <p>
        Em conformidade com a LGPD, nosso Encarregado pelo Tratamento de Dados Pessoais pode ser
        contatado por:
    </p>

    <p><strong>E-mail:</strong> <strong>contato@rolle.com.br</strong></p>

    <h2>11. Privacidade de menores</h2>

    <p>
        O Serviço destina-se a pessoas com <strong>18 anos ou mais</strong>. Não coletamos
        intencionalmente dados pessoais de menores de 18 anos sem o consentimento de seus pais ou
        responsáveis legais. Caso tomemos conhecimento de que coletamos dados de um menor sem a
        devida autorização, os eliminaremos prontamente.
    </p>

    <h2>12. Alterações nesta Política</h2>

    <p>
        Podemos atualizar esta Política de Privacidade periodicamente. Notificaremos você sobre
        alterações relevantes publicando a versão atualizada nesta página e modificando a data de
        "Última atualização". O uso continuado do Serviço após as alterações constitui ciência da
        Política atualizada.
    </p>

